import { describe, it, expect, beforeEach, vi } from 'vitest'
import { mount } from '@vue/test-utils'
import ResultTable from '../src/blocks/ResultTable.vue'
import { setLocale } from '../src/i18n'

const make = (rows: unknown[][], cols = 2, truncated = false) => ({
  columns: Array.from({ length: cols }, (_, i) => ({ name: `c${i}` })),
  rows, truncated, elapsedMs: 12, dbType: 'x',
})

const clickD = (el: any, detail: number) => el.element.dispatchEvent(new MouseEvent('click', { detail, bubbles: true }))

describe('ResultTable', () => {
  beforeEach(() => setLocale('zh-CN'))
  it('virtualizes 5000x50', () => {
    const rows = Array.from({ length: 5000 }, (_, r) => Array.from({ length: 50 }, (_, c) => r * c))
    const w = mount(ResultTable, { props: { result: make(rows, 50) } })
    const n = w.findAll('tbody tr[data-row]').length
    expect(n).toBeGreaterThan(0)
    expect(w.findAll('tr').length).toBeLessThan(200)
    expect(w.text()).toContain('5000')
    expect(w.text()).toContain('12')
  })
  it('sorts asc, desc, none numerically with NULLs last', async () => {
    const w = mount(ResultTable, { props: { result: make([[10, 'a'], [2, 'b'], [null, 'c'], [33, 'd']]) } })
    const first = () => w.find('tbody tr[data-row] td[data-c]').text()
    expect(first()).toBe('10')
    await w.findAll('th')[1].trigger('click')
    expect(first()).toBe('2')
    await w.findAll('th')[1].trigger('click')
    expect(first()).toBe('33')
    expect(w.findAll('tbody tr[data-row]')[3].find('td[data-c]').classes()).toContain('cell-null')
    await w.findAll('th')[1].trigger('click')
    expect(first()).toBe('10')
  })
  it('NULL cell', () => {
    const w = mount(ResultTable, { props: { result: make([[null, 1]]) } })
    const td = w.find('td.cell-null')
    expect(td.text()).toBe('NULL')
  })
  it('truncated banner and title', () => {
    const w = mount(ResultTable, { props: { result: make([['long text', 1]], 2, true) } })
    expect(w.text()).toContain('结果已截断（最多 5000 行）')
    expect(w.find('td[data-c]').attributes('title')).toBe('long text')
    setLocale('en')
    const w2 = mount(ResultTable, { props: { result: make([], 2, true) } })
    expect(w2.text()).toContain('truncated')
  })
  it('resets window when result shrinks after scrolling', async () => {
    const big = Array.from({ length: 1000 }, (_, i) => [i, 'x'])
    const w = mount(ResultTable, { props: { result: make(big) } })
    const vp = w.find('.viewport')
    ;(vp.element as HTMLElement).scrollTop = 20000
    await vp.trigger('scroll')
    await w.setProps({ result: make([[1, 'a'], [2, 'b'], [3, 'c'], [4, 'd'], [5, 'e']]) })
    expect(w.findAll('tbody tr[data-row]')).toHaveLength(5)
    expect((vp.element as HTMLElement).scrollTop).toBe(0)
  })
  it('keyboard sort with aria-sort', async () => {
    const w = mount(ResultTable, { props: { result: make([[3, 'a'], [1, 'b']]) } })
    const th = () => w.findAll('th')[1]
    expect(th().attributes('aria-sort')).toBe('none')
    expect(th().attributes('scope')).toBe('col')
    expect(th().attributes('tabindex')).toBe('0')
    await th().trigger('keydown', { key: 'Enter' })
    expect(th().attributes('aria-sort')).toBe('ascending')
    expect(w.find('tbody tr[data-row] td[data-c]').text()).toBe('1')
    await th().trigger('keydown', { key: ' ' })
    expect(th().attributes('aria-sort')).toBe('descending')
  })

  const cells = (w: any) => w.findAll('tbody tr[data-row]')
  const td = (w: any, r: number, c: number) => cells(w)[r].findAll('td[data-c]')[c]
  const data = () => make([[3, 'a', true], [1, 'b', false], [2, '', null]], 3)

  it('row number column follows sort', async () => {
    const w = mount(ResultTable, { props: { result: data() } })
    expect(w.findAll('th')[0].text()).toBe('#')
    expect(cells(w).map((r: any) => r.find('.rowno').text())).toEqual(['1', '2', '3'])
    await w.findAll('th')[1].trigger('click')
    expect(td(w, 0, 0).text()).toBe('1')
    expect(cells(w)[0].find('.rowno').text()).toBe('1')
  })
  it('click, shift-click, row, column selection', async () => {
    const w = mount(ResultTable, { props: { result: data() } })
    await td(w, 0, 0).trigger('mousedown')
    expect(td(w, 0, 0).classes()).toContain('selected')
    await td(w, 1, 1).trigger('mousedown', { shiftKey: true })
    expect(w.findAll('td.selected')).toHaveLength(4)
    expect(w.text()).toContain('已选 2×2')
    await cells(w)[2].find('.rowno').trigger('mousedown')
    expect(w.findAll('td.selected')).toHaveLength(3)
    await w.findAll('th')[2].trigger('dblclick')
    expect(w.findAll('td.selected')).toHaveLength(3)
    expect(td(w, 0, 1).classes()).toContain('selected')
  })
  it('keyboard navigation, select all, escape', async () => {
    const w = mount(ResultTable, { props: { result: data() } })
    const vp = w.find('.viewport')
    await vp.trigger('keydown', { key: 'ArrowDown' })
    expect(td(w, 0, 0).classes()).toContain('selected')
    await vp.trigger('keydown', { key: 'ArrowDown' })
    await vp.trigger('keydown', { key: 'ArrowRight' })
    expect(td(w, 1, 1).classes()).toContain('selected')
    await vp.trigger('keydown', { key: 'ArrowDown', shiftKey: true })
    expect(w.findAll('td.selected')).toHaveLength(2)
    await vp.trigger('keydown', { key: 'a', ctrlKey: true })
    expect(w.findAll('td.selected')).toHaveLength(9)
    await vp.trigger('keydown', { key: 'Escape' })
    expect(w.findAll('td.selected')).toHaveLength(0)
  })
  it('arrow scrolls selection into view', async () => {
    const big = Array.from({ length: 100 }, (_, i) => [i, 'x'])
    const w = mount(ResultTable, { props: { result: make(big), viewportHeight: 100 } })
    const vp = w.find('.viewport')
    await td(w, 0, 0).trigger('mousedown')
    for (let i = 0; i < 20; i++) await vp.trigger('keydown', { key: 'ArrowDown' })
    expect((vp.element as HTMLElement).scrollTop).toBeGreaterThan(0)
  })
  it('selection survives scrolling away and back', async () => {
    const big = Array.from({ length: 1000 }, (_, i) => [i, 'x'])
    const w = mount(ResultTable, { props: { result: make(big) } })
    const vp = w.find('.viewport')
    await td(w, 0, 0).trigger('mousedown')
    ;(vp.element as HTMLElement).scrollTop = 20000
    await vp.trigger('scroll')
    expect(w.findAll('td.selected')).toHaveLength(0)
    ;(vp.element as HTMLElement).scrollTop = 0
    await vp.trigger('scroll')
    expect(td(w, 0, 0).classes()).toContain('selected')
  })
  it('copies TSV, with header on shift, nothing without selection', async () => {
    const writeText = vi.fn().mockResolvedValue(undefined)
    Object.defineProperty(navigator, 'clipboard', { value: { writeText }, configurable: true })
    const w = mount(ResultTable, { props: { result: data() } })
    const vp = w.find('.viewport')
    await vp.trigger('keydown', { key: 'c', ctrlKey: true })
    expect(writeText).not.toHaveBeenCalled()
    await td(w, 0, 0).trigger('mousedown')
    await td(w, 1, 1).trigger('mousedown', { shiftKey: true })
    await vp.trigger('keydown', { key: 'c', ctrlKey: true })
    expect(writeText).toHaveBeenLastCalledWith('3\ta\n1\tb')
    await vp.trigger('keydown', { key: 'C', metaKey: true, shiftKey: true })
    expect(writeText).toHaveBeenLastCalledWith('c0\tc1\n3\ta\n1\tb')
  })
  it('resizes column and resets on dblclick', async () => {
    const w = mount(ResultTable, { props: { result: data() } })
    const col = () => w.findAll('col')[1]
    const w0 = parseInt(col().attributes('style')!.match(/width:\s*(\d+)/)![1])
    const h = w.findAll('.resize')[0]
    await h.trigger('mousedown', { clientX: 100 })
    document.dispatchEvent(new MouseEvent('mousemove', { clientX: 140, bubbles: true }))
    document.dispatchEvent(new MouseEvent('mouseup', { bubbles: true }))
    await w.vm.$nextTick()
    expect(parseInt(col().attributes('style')!.match(/width:\s*(\d+)/)![1])).toBe(w0 + 40)
    await h.trigger('dblclick')
    expect(parseInt(col().attributes('style')!.match(/width:\s*(\d+)/)![1])).toBe(w0)
  })
  it('typed cells', () => {
    const w = mount(ResultTable, { props: { result: data() } })
    expect(td(w, 0, 0).classes()).toContain('num')
    expect(td(w, 0, 1).classes()).not.toContain('num')
    expect(td(w, 0, 2).text()).toBe('true')
    expect(td(w, 0, 2).classes()).toContain('bool')
    expect(td(w, 2, 1).text()).toBe('')
    expect(td(w, 2, 1).classes()).not.toContain('cell-null')
    expect(td(w, 2, 2).text()).toBe('NULL')
  })
  it('emits cell-detail on dblclick and space; long marker', async () => {
    const w = mount(ResultTable, { props: { result: make([[3, { a: 1 }]]) } })
    expect(td(w, 0, 1).text()).toContain('⤢')
    expect(td(w, 0, 0).text()).not.toContain('⤢')
    await td(w, 0, 1).trigger('dblclick')
    expect(w.emitted('cell-detail')![0][0]).toEqual({ row: 0, col: 1, value: { a: 1 }, column: 'c1' })
    await td(w, 0, 0).trigger('mousedown')
    await w.find('.viewport').trigger('keydown', { key: ' ' })
    expect(w.emitted('cell-detail')![1][0]).toEqual({ row: 0, col: 0, value: 3, column: 'c0' })
  })
  it('empty and zero-column results', () => {
    const w = mount(ResultTable, { props: { result: make([], 2) } })
    expect(w.text()).toContain('无数据')
    const w2 = mount(ResultTable, { props: { result: make([], 0) } })
    expect(w2.text()).toContain('无数据')
  })

  it('header dblclick keeps sort and selects column', async () => {
    const w = mount(ResultTable, { props: { result: data() } })
    const th = w.findAll('th')[1]
    clickD(th, 1)
    clickD(th, 2)
    await th.trigger('dblclick')
    expect(th.attributes('aria-sort')).toBe('none')
    expect(td(w, 0, 0).text()).toBe('3')
    expect(w.findAll('td.selected')).toHaveLength(3)
  })
  it('sort change clears selection', async () => {
    const writeText = vi.fn().mockResolvedValue(undefined)
    Object.defineProperty(navigator, 'clipboard', { value: { writeText }, configurable: true })
    const w = mount(ResultTable, { props: { result: data() } })
    await td(w, 0, 0).trigger('mousedown')
    await w.findAll('th')[1].trigger('click')
    expect(w.findAll('td.selected')).toHaveLength(0)
    await w.find('.viewport').trigger('keydown', { key: 'c', ctrlKey: true })
    expect(writeText).not.toHaveBeenCalled()
  })
  it('row number mousedown focuses viewport', async () => {
    const w = mount(ResultTable, { props: { result: data() }, attachTo: document.body })
    await cells(w)[0].find('.rowno').trigger('mousedown')
    expect(document.activeElement).toBe(w.find('.viewport').element)
    await w.find('.viewport').trigger('keydown', { key: 'ArrowDown' })
    expect(td(w, 1, 2).classes()).toContain('selected')
    w.unmount()
  })
  it('shows copy failed and a11y attributes', async () => {
    Object.defineProperty(navigator, 'clipboard', { value: { writeText: vi.fn().mockRejectedValue(new Error('x')) }, configurable: true })
    const w = mount(ResultTable, { props: { result: data() } })
    expect(w.find('.viewport').attributes('role')).toBe('grid')
    await td(w, 0, 0).trigger('mousedown')
    expect(td(w, 0, 0).attributes('aria-selected')).toBe('true')
    expect(td(w, 0, 0).attributes('aria-colindex')).toBe('2')
    await w.find('.viewport').trigger('keydown', { key: 'c', ctrlKey: true })
    await new Promise((r) => setTimeout(r, 0))
    await w.vm.$nextTick()
    expect(w.text()).toContain('复制失败')
    await td(w, 1, 0).trigger('mousedown')
    expect(w.text()).not.toContain('复制失败')
  })
  it('empty grids do not throw on keys and header', async () => {
    for (const r of [make([], 2), make([], 0)]) {
      const w = mount(ResultTable, { props: { result: r } })
      const vp = w.find('.viewport')
      await vp.trigger('keydown', { key: 'ArrowDown' })
      await vp.trigger('keydown', { key: 'c', ctrlKey: true })
      await vp.trigger('keydown', { key: 'a', ctrlKey: true })
      const th = w.findAll('th')[1]
      if (th) { await th.trigger('click'); await th.trigger('dblclick') }
    }
  })
  it('marks the row-number th/td as frozen (rowno) and keeps colgroup width', () => {
    const w = mount(ResultTable, { props: { result: make([[1, 2], [3, 4]]) } })
    expect(w.find('thead th').classes()).toContain('rowno')
    const tds = w.findAll('tbody tr[data-row] td:first-child')
    expect(tds.length).toBe(2)
    tds.forEach((td) => expect(td.classes()).toContain('rowno'))
    expect(w.find('colgroup col').attributes('style')).toContain('width: 48px')
  })
})

describe('ResultTable saved label', () => {
  const iso = '2026-01-02T03:04:05.000Z'
  it('shows zh label with formatted time', () => {
    setLocale('zh-CN')
    const w = mount(ResultTable, { props: { result: make([[1, 2]]), savedAt: iso } })
    const el = w.find('[data-test=saved-label]')
    expect(el.text()).toMatch(/^已保存的结果 · /)
    expect(el.text()).toContain(new Intl.DateTimeFormat('zh-CN', { dateStyle: 'medium', timeStyle: 'medium' }).format(new Date(iso)))
  })
  it('shows en label; falls back to raw string when invalid', () => {
    setLocale('en')
    const w = mount(ResultTable, { props: { result: make([[1, 2]]), savedAt: iso } })
    expect(w.find('[data-test=saved-label]').text()).toMatch(/^Saved result · /)
    expect(w.find('[data-test=saved-label]').text()).toContain(new Intl.DateTimeFormat('en', { dateStyle: 'medium', timeStyle: 'medium' }).format(new Date(iso)))
    const w2 = mount(ResultTable, { props: { result: make([[1, 2]]), savedAt: 'garbage' } })
    expect(w2.find('[data-test=saved-label]').text()).toBe('Saved result · garbage')
  })
  it('no label without savedAt', () => {
    const w = mount(ResultTable, { props: { result: make([[1, 2]]) } })
    expect(w.find('[data-test=saved-label]').exists()).toBe(false)
  })
  it('partial banner only when partial; coexists with truncated', () => {
    setLocale('zh-CN')
    const none = mount(ResultTable, { props: { result: make([[1, 2]]) } })
    expect(none.find('[data-test=partial-banner]').exists()).toBe(false)
    const w = mount(ResultTable, { props: { result: make([[1, 2]], 2, true), partial: true } })
    expect(w.find('[data-test=partial-banner]').text()).toBe('基于部分数据：上游结果被截断，本结果可能不完整（可在开始页的设置中调整每块最多行数）')
    expect(w.text()).toContain('结果已截断')
    setLocale('en')
    const e = mount(ResultTable, { props: { result: make([[1, 2]]), partial: true } })
    expect(e.find('[data-test=partial-banner]').text()).toBe('Based on partial data: an upstream result was truncated, so this result may be incomplete (raise "Max rows per block" in the start page settings)')
    expect(e.text()).not.toContain('Result truncated')
  })
  it('visualize button: enabled with columns, emits, disabled without', async () => {
    setLocale('zh-CN')
    const w = mount(ResultTable, { props: { result: make([[1, 2]]) } })
    const b = w.find('[data-test="visualize"]')
    expect(b.text()).toBe('可视化'); expect(b.attributes('aria-label')).toBe('可视化')
    expect((b.element as HTMLButtonElement).disabled).toBe(false)
    await b.trigger('click'); expect(w.emitted('visualize')).toHaveLength(1)
    setLocale('en')
    await w.vm.$nextTick()
    const w2 = mount(ResultTable, { props: { result: make([], 0) } })
    expect((w2.find('[data-test="visualize"]').element as HTMLButtonElement).disabled).toBe(true)
    expect(w2.find('[data-test="visualize"]').attributes('aria-label')).toBe('Visualize')
  })
})
