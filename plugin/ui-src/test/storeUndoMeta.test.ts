import { describe, it, expect, vi } from 'vitest'
import { mkStore } from './undoHelpers'

describe('undo: metadata, input, big-number, settings', () => {
  it('updateMeta/removeMetaKey undo restores key order byte-identically', () => {
    const { s, text } = mkStore()
    const orig = text()
    s.updateMeta('s1', { maxRows: 10 })
    s.removeMetaKey('s1', 'connection')
    s.updateMeta('s1', { source: 'results' })
    while (s.history.canUndo.value) s.undo()
    expect(text()).toBe(orig); expect(s.dirty.value).toBe(false)
  })
  it('input block: value, variable, type change (grouped) undo/redo', () => {
    const { s, blk, text } = mkStore()
    const orig = text()
    s.updateMeta('i1', { value: 2 })
    s.updateMeta('i1', { variable: 'w' })
    s.editBlock('i1', () => { s.updateMeta('i1', { inputType: 'text' }); s.removeMetaKey('i1', 'options'); s.updateMeta('i1', { value: 'x' }) })
    expect(s.history.undoDepth.value).toBe(3)
    s.undo(); expect(blk('i1').metadata).toEqual({ variable: 'w', inputType: 'select', options: [1, 2, 3], value: 2 })
    s.undo(); s.undo(); expect(text()).toBe(orig)
    s.redo(); expect(blk('i1').metadata.value).toBe(2)
  })
  it('big-number: field/aggregate/label/filter/compare/data edits, add/remove/move metric: one step each; undo reschedules refresh', () => {
    vi.useFakeTimers()
    const { s, blk, text } = mkStore()
    const runner = vi.fn(async () => ({}) as any)
    s.setBigNumberRunner(runner)
    const orig = text()
    s.setBigNumber('n1', { field: 'qty' })
    s.setBigNumber('n1', { aggregate: 'avg' })
    s.setBigNumber('n1', { label: 'L' })
    s.setBigNumber('n1', { filter: [{ field: 'region', op: 'eq', value: 'a' } as any] })
    s.setBigNumber('n1', { compare: { kind: 'previous', dateField: 'd' } as any })
    s.setBigNumber('n1', { data: 'other' })
    s.addBigNumberMetric('n1')
    s.moveBigNumberMetric('n1', 1, -1)
    s.removeBigNumberMetric('n1', 0)
    expect(s.history.undoDepth.value).toBe(9)
    vi.advanceTimersByTime(500); runner.mockClear()
    s.undo(); vi.advanceTimersByTime(500)
    expect(runner).toHaveBeenCalledWith('n1')
    while (s.history.canUndo.value) s.undo()
    expect(text()).toBe(orig); expect(s.dirty.value).toBe(false)
    expect(blk('n1').metadata.value.field).toBe('amount')
    vi.useRealTimers()
  })
  it('setBigNumber label coalesces with a key only when asked', () => {
    const { s } = mkStore()
    s.setBigNumber('n1', { label: 'a' }, { coalesce: true })
    s.setBigNumber('n1', { label: 'ab' }, { coalesce: true })
    expect(s.history.undoDepth.value).toBe(1)
  })
  it('setDefaultConnection undo removes the auto-added connection entry; catalog and outputs mode undo', () => {
    const { s, text } = mkStore()
    const orig = text()
    s.setDefaultConnection('pg', 'postgres')
    expect(s.nb.value.connections).toEqual([{ name: 'pg', dialect: 'postgres' }])
    s.setDefaultCatalog('db', 'sc')
    s.setOutputsMode('inline')
    s.setOutputsMode('inline')
    expect(s.history.undoDepth.value).toBe(3)
    while (s.history.canUndo.value) s.undo()
    expect(text()).toBe(orig); expect(s.nb.value.connections).toEqual([])
    s.redo(); expect(s.nb.value.settings.defaultConnection).toBe('pg')
  })
  it('setTransposed undo restores metadata.clients and the transposed map', () => {
    const { s, blk, text } = mkStore()
    const orig = text()
    s.setTransposed('s1', true)
    expect(s.transposed.get('s1')).toBe(true)
    s.undo()
    expect(s.transposed.get('s1')).toBeUndefined(); expect(text()).toBe(orig)
    s.redo(); expect(s.transposed.get('s1')).toBe(true); expect(blk('s1').metadata.clients.dbx.transposed).toBe(true)
  })
  it('execution state, derived writes and modifiedAt are not recorded', () => {
    const { s } = mkStore()
    s.runs.set('s1', { status: 'ok' } as any)
    s.toText()
    expect(s.history.undoDepth.value).toBe(0)
  })
  it('labels are history.label keys', () => {
    const { s } = mkStore()
    s.updateContent('s1', 'x'); s.updateContent('m1', 'y'); s.updateMeta('i1', { value: 3 }); s.setBigNumber('n1', { field: 'q' }); s.updateMeta('s1', { maxRows: 5 })
    const labels: string[] = []
    while (s.history.canUndo.value) { const r = s.undo(); if (r.ok) labels.push(r.entry.label) }
    expect(labels).toEqual(['history.label.editMeta', 'history.label.editBigNumber', 'history.label.editInput', 'history.label.editMarkdown', 'history.label.editSql'])
  })
})
