// Precompiles spec/sqlnb-v1.schema.json into a standalone validator so that
// no `new Function` (CSP 'unsafe-eval') is needed at runtime inside the DBX sandbox.
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = resolve(here, '../../../spec/sqlnb-v1.schema.json');
const outPath = resolve(here, '../src/schemaValidator.generated.js');

export function generate() {
  const schema = JSON.parse(readFileSync(schemaPath, 'utf8'));
  const Ctor = Ajv2020.default ?? Ajv2020;
  const ajv = new Ctor({ allErrors: true, strict: false, code: { source: true, esm: true, optimize: true } });
  const validate = ajv.compile(schema);
  let code = standaloneCode(ajv, validate);
  // Ajv's standalone output pulls runtime helpers via CommonJS require(); inline them
  // so the module is plain ESM with no imports and no eval (works in the DBX sandbox).
  const ucs2 = 'const ucs2length = (str) => { const len = str.length; let length = 0, pos = 0, value; while (pos < len) { length++; value = str.charCodeAt(pos++); if (value >= 0xd800 && value <= 0xdbff && pos < len) { value = str.charCodeAt(pos); if ((value & 0xfc00) === 0xdc00) pos++; } } return length; };';
  code = code.replace(/const (\w+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/g, (_m, name) => ucs2 + `const ${name} = ucs2length;`);
  if (/require\(/.test(code)) throw new Error('generated validator still contains require(); add an inline replacement');
  return '// GENERATED by scripts/gen-validator.mjs from spec/sqlnb-v1.schema.json — do not edit.\n// @ts-nocheck\n' + code;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(outPath, generate());
  console.log('wrote', outPath);
}
